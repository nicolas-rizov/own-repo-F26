CREATE TYPE school_year_t AS ENUM ('Sophomore', 'Junior', 'Senior');
CREATE TYPE intro_programming_t AS ENUM ('took_it', 'equivalent', 'neither');

CREATE TABLE students (
    netid                   VARCHAR(16)          NOT NULL,
    name                    TEXT                 NOT NULL,
    school_year             school_year_t        NOT NULL,
    intro_programming       intro_programming_t  NOT NULL,
    skill_programming       SMALLINT             NOT NULL,
    skill_data_stats        SMALLINT             NOT NULL,
    skill_frontend_design   SMALLINT             NOT NULL,
    skill_business_pitch    SMALLINT             NOT NULL,
    working_style           TEXT                 NOT NULL,
    interests               TEXT                 NOT NULL,
    semester_goal           TEXT                 NOT NULL,
    submitted_at            TIMESTAMPTZ          NOT NULL,

    CONSTRAINT students_pkey PRIMARY KEY (netid),
    CONSTRAINT skill_programming_range
        CHECK (skill_programming BETWEEN 1 AND 5),
    CONSTRAINT skill_data_stats_range
        CHECK (skill_data_stats BETWEEN 1 AND 5),
    CONSTRAINT skill_frontend_design_range
        CHECK (skill_frontend_design BETWEEN 1 AND 5),
    CONSTRAINT skill_business_pitch_range
        CHECK (skill_business_pitch BETWEEN 1 AND 5)
);

CREATE TABLE tools (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    TEXT                 NOT NULL,

    CONSTRAINT tools_name_key UNIQUE (name)
);

CREATE TABLE availability (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot                    TEXT                 NOT NULL,

    CONSTRAINT availability_slot_key UNIQUE (slot)
);

CREATE TABLE student_tools (
    netid                   VARCHAR(16)          NOT NULL,
    tool_id                 INTEGER              NOT NULL,

    CONSTRAINT student_tools_pkey PRIMARY KEY (netid, tool_id),
    CONSTRAINT student_tools_netid_fkey
        FOREIGN KEY (netid) REFERENCES students (netid) ON DELETE CASCADE,
    CONSTRAINT student_tools_tool_id_fkey
        FOREIGN KEY (tool_id) REFERENCES tools (id) ON DELETE CASCADE
);

CREATE TABLE student_availability (
    netid                   VARCHAR(16)          NOT NULL,
    availability_id         INTEGER              NOT NULL,

    CONSTRAINT student_availability_pkey PRIMARY KEY (netid, availability_id),
    CONSTRAINT student_availability_netid_fkey
        FOREIGN KEY (netid) REFERENCES students (netid) ON DELETE CASCADE,
    CONSTRAINT student_availability_availability_id_fkey
        FOREIGN KEY (availability_id) REFERENCES availability (id) ON DELETE CASCADE
);

CREATE INDEX students_submitted_at_idx
    ON students (submitted_at);

CREATE INDEX student_tools_tool_id_idx
    ON student_tools (tool_id);

CREATE INDEX student_availability_availability_id_idx
    ON student_availability (availability_id);
